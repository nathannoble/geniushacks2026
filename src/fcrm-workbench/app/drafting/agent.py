"""M6 — Draft Assessment.

Synthesizes M2's facts, M3's policy citations, M4's screening report, and
M5's risk score into the structured memo an FCRM analyst reviews at Gate 1.

Citations are built deterministically from the actual structured inputs,
never generated by the model — the same "explain, don't invent" principle
as M5's rationale. Claude's one call is used only for the summary, open
questions, and suggested conditions, which genuinely need synthesis rather
than a citation trail.
"""
from __future__ import annotations

import os

from anthropic import Anthropic

from app.common.json_utils import parse_json_safely
from app.retrieval.schema import PolicyCitation
from app.scoring.schema import RiskScore
from app.screening.schema import ScreeningReport

from .schema import DraftMemo, MemoCitation

_client: Anthropic | None = None


def _get_client() -> Anthropic:
    global _client
    if _client is None:
        _client = Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
    return _client


_MODEL = "claude-sonnet-5"

_SYSTEM_PROMPT = (
    "You draft the FCRM (Financial Crimes Risk Management) assessment memo an "
    "analyst reviews before a case goes to committee. Synthesize the case facts, "
    "policy citations, screening report, and risk score you're given into a memo. "
    "You do not change the risk tier or invent facts not present in the input — "
    "your job is synthesis and identifying open questions, not re-deciding the case.\n\n"
    'Respond ONLY with JSON in this shape: {"summary": "2-4 sentence overview", '
    '"open_questions": ["..."], "suggested_conditions": ["..."]}. '
    "suggested_conditions should be empty unless the risk tier or screening results "
    "clearly warrant conditions; open_questions should flag anything genuinely "
    "ambiguous or missing from the input, not restate the facts you were given."
)


def _build_citations(facts, policy_citations: list[PolicyCitation], screening: ScreeningReport) -> list[MemoCitation]:
    citations: list[MemoCitation] = []
    for f in facts:
        citations.append(
            MemoCitation(
                source=f"M2 extraction: {f.source_document}, {f.source_location}",
                excerpt=f"{f.field}: {f.value}",
            )
        )
    for c in policy_citations:
        citations.append(MemoCitation(source=f"M3 policy: {c.policy_id} — {c.title}", excerpt=c.excerpt))
    for m in screening.matches:
        if m.status != "no_hit":
            citations.append(
                MemoCitation(
                    source=f"M4 screening: {m.party_name}",
                    excerpt=f"{m.status} against {m.matched_entry} (confidence {m.confidence})",
                )
            )
    return citations


def draft_assessment(
    case_id: str,
    facts,
    policy_citations: list[PolicyCitation],
    screening: ScreeningReport,
    risk_score: RiskScore,
) -> DraftMemo:
    facts_text = "\n".join(
        f"- {f.field}: {f.value} ({f.source_document}, {f.source_location})" for f in facts
    )
    citations_text = "\n".join(f"- {c.policy_id} ({c.title}): {c.excerpt[:200]}" for c in policy_citations)
    screening_text = "\n".join(f"- {m.party_name}: {m.status} (matched {m.matched_entry})" for m in screening.matches)
    score_text = f"Tier: {risk_score.tier} (weighted total {risk_score.weighted_total})\nRationale: {risk_score.rationale}"

    user_content = (
        f"Case facts:\n{facts_text or '(none extracted)'}\n\n"
        f"Policy citations:\n{citations_text or '(none retrieved)'}\n\n"
        f"Screening report:\n{screening_text or '(no parties screened)'}\n\n"
        f"Risk score:\n{score_text}"
    )

    response = _get_client().messages.create(
        model=_MODEL,
        max_tokens=1500,
        system=_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_content}],
    )
    parsed = parse_json_safely(response.content[0].text, default={})
    if not isinstance(parsed, dict):
        parsed = {}

    return DraftMemo(
        case_id=case_id,
        risk_tier=risk_score.tier,
        summary=parsed.get("summary") or "Summary unavailable — model response could not be parsed.",
        citations=_build_citations(facts, policy_citations, screening),
        open_questions=parsed.get("open_questions") or [],
        suggested_conditions=parsed.get("suggested_conditions") or [],
    )
